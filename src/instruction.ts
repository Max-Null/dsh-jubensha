/**
 * 把「选好的阵容」写成一段话，交给主持人。
 *
 * **为什么是生成一段文本，而不是面板自己去调工具**：设计方案 §5 拍板记录第 4 条把界面定为
 * **附加层**——宿主侧的工具与状态机不得依赖客户端存在。面板一旦会发号施令，它就从「另一块屏」
 * 变成了「第二条控制通道」，而那条约束是靠**面板只产出文本**守住的，不是靠自觉。
 *
 * 顺带解决一件小事：用户不必去记 `jubensha_player` 的参数长什么样。
 *
 * 这是个零依赖的纯函数，所以浏览器半边引得起，也测得了。
 *
 * @module @max-null/dsh-jubensha/instruction
 */
import type { RoomCase } from './room-types.ts'

/** 排好的一个位子。 */
export interface SeatAssignment {
  /** 座位 id。 */
  readonly seat: string
  /** 这个位子演谁。 */
  readonly roleName: string
  /** 谁来演——演员池里的 id。 */
  readonly actorId: string
  /** 演员的名字，写给人看的那一份。 */
  readonly actorName: string
}

/**
 * 写一段交给主持人的开局指令。
 *
 * 它**不替主持人决定**：角色本怎么取、上桌顺序、开局第一句说什么，都留着。这里给的是
 * 那一局的骨架——本子在哪、谁坐哪、谁演谁——剩下的按本子与人的现场判断来。
 * @param entry - 选中的本子。
 * @param assignment - 排好的座位；只含 AI 位子，真人位子不在这里（它是你自己）。
 * @returns 一段可以直接粘进对话的文本。
 */
export function openingInstruction(entry: RoomCase, assignment: readonly SeatAssignment[]): string {
  const seats = entry.roles.map(role => role.id)
  const human = entry.roles.filter(role => role.player === 'human').map(role => role.id)
  const lines = [
    `开一局《${entry.title}》（case ${entry.id}）——**这一局要用团队模式**。`,
    '',
    '（第 ③ 步要让几位 AI 玩家上桌，而那是靠 team 的 spawn_teammate 创建的；DSH 默认不开团队，',
    '  所以要在这条消息里说清。少了这句，前两步会照常成功，第三步却报「这个部署里没有',
    '  agent-team 服务」——那看着像插件坏了，其实只差这一句。）',
    '',
    '① 取本子（先 load，它会顺带报出格式问题）：',
    `   jubensha_case —— action="load", dir="${entry.path}"`,
    '',
    '② 开局：',
    `   jubensha_state —— action="start", caseId="${entry.id}", title="${entry.title}", `
      + `seats=${JSON.stringify(seats)}, humanSeat="${human[0] ?? ''}"`,
  ]
  if (assignment.length > 0) {
    lines.push(
      '',
      '③ 让这几位上桌（这一步是唯一需要团队模式的）。**一座一份**：用 jubensha_case '
        + 'action="book" 取到的是那个座位的引用，原样填进 roleBook，别转述、别换座位；'
        + 'actor 是他跨局的身份：',
    )
    for (const one of assignment) {
      lines.push(`   ${one.seat} ${one.roleName} → actor="${one.actorId}"（${one.actorName}）`)
    }
  }
  lines.push(
    '',
    '--- 带一局的七条规矩（每一条都是实测逼出来的，别跳） ---',
    '',
    '① **真人是这张桌子上唯一会等的人。** AI 玩家会一直说下去，而真人不会自己出现——他坐在那儿'
      + '看着，等你给他一个落点。所以「他没说话」永远是你的问题，不是他的。'
      + '（少了这条，DM 会把四个阶段一口气推完、一次都不叫他。2026-10-06 用户报的。）',
    '',
    '② **AI 这边每说两三个来回，就停下来给他一次落点。** `say` 与 `relay` **都算**——'
      + '转达玩家之间的话十几轮而不叫他，与推三个阶段是同一个效果（实测：`say` 两次、`relay` 十二次，'
      + '真人一句没说）。停下来 = 在对话里对他说一句话，**然后结束这一轮**，不要再调任何工具。',
    '',
    '③ **给他落点的时候，别把选项替他排好。** 问题要具体到他能直接答（「你那半小时在哪儿」好过'
      + '「你想说什么」）；而给他 A／B／C 三选一、还标上哪个好，等于你替他把这一轮玩完了'
      + '（用户原话：「作为 DM 的主 agent 给我都推荐完了，我都没说话」）。',
    '',
    '④ **一次只把话头交给一个人。** 别把三个人的话一口气推完——一个人说完，停一下，看真人接不接；'
      + '他不接，你再叫下一个。**注意这不是回合制**：剧本杀本来就没有轮次上限，只有自我介绍按顺序，'
      + '所以不必造一个轮流发言的框。',
    '',
    '⑤ **先把人叫齐，再开场；而自述第一个就是他。**\n'
      + '　· **人齐了才说话。** 座位里还有人没上桌（`jubensha_player action="list"` 的 '
      + '`notSeated` 会告诉你还缺谁），就继续 `spawn`——**在所有人上桌之前，谁都不许开口**。'
      + '先上桌的那几位不会自己抢话，他们等着你叫（实测的错法是：DM 一边 spawn 一边让先上桌的人'
      + '说话，第三个人上桌的节奏就被打断了——2026-10-07 用户报的「小满还没上桌，阿May 就开始'
      + '问我了」）。有一条闸看着这件事：桌上缺人时说话会被拦下来。\n'
      + '　· 全桌上桌之后，**从真人开始**请他自述——座位顺序里 `p0` 是他，而「一个个请他们上桌」'
      + '天然从他开始（用户报过：三个 AI 先聊起来了，而他的板子上还写着「还没上桌」）。'
      + '你不需要、也不该替他说。',
    '',
    '⑥ **不许替他发言，也不许替任何人编台词。** 「你说过 X」这种引述只在**他真的说过**时用得上'
      + '——对着一个没开口的人说「你说过」，他会当场回你一句「我没说过」（用户报的：AI 玩家对着'
      + '还没开口的真人说「你说你 21:45 走的」）。你知道的事照实说，要问就直接问。',
    '',
    '⑦ **听到行踪就顺手记一笔**（`jubensha_state action="timeline"`）：某人说「我十点半走的」，'
      + '你就记一条 `{at:"22:30", seat:"p2", doing:"从正门离开"}`。一条只记一件事，照他说的记，'
      + '别替他补、也别替他圆。',
    '',
    '**⑦ 里那个 `at` 是这一栏最容易写错的地方**——写之前把原话里的时刻对一遍：「八点一刻」是'
      + '`20:15`、「八点整」是 `20:00`、「十点二十」是 `22:20`。别按"夜里的第几个小时"去推，'
      + '那一栏按 `at` 排序，写错一个数整张时间线就散了（用户报的：三条里三条都错，而每一句里'
      + '他自己都带着正确的时间）。**拿不准就别换算，照原话的数字写。**',
    '',
    '⑧ **搜证那一页不能空着过去，而发线索是两步。** 进到搜证阶段之后：\n'
      + '　① `jubensha_case action="clue"` —— 把线索**正文**捞出来，贴到桌上给玩家看；\n'
      + '　② `jubensha_state action="reveal" clues=["c1","c2",…]` —— 把线索 **id 记进局面**，'
      + '房间页左栏那一页读的是它。\n'
      + '**两步都要做。** 只做①的话玩家看得见你在对话里念线索，而房间页那一页是空的'
      + '（用户 2026-10-06 实测遇到的：一路推到投票，一条线索都没摆出来）。\n'
      + '而线索**一次给全**——别只给被怀疑的那个人相关的那几条，那等于替玩家判案。'
      + '有一条闸看着这件事：一条都没记进局面时，那个阶段的推进会被拦下来。',
    '',
    '（有一条闸在看着 ②：AI 这边连说三次而真人一句没说，你会被拦下来一次。被拦了就是把话头'
      + '交给他、然后停下——那不是出错，是提醒。）',
    '',
    '**这七条的完整版是一条 skill（`jubensha-dm`）**——每一条都写着它是哪一局踩出来的，'
      + '还有几条反直觉的补充。带局带到一半拿不准（该不该替他做选择、这条行踪要不要记、'
      + 'AI 是不是聊太久了），随时去读它。',
    '',
    '剩下的按本子来——开局第一句、什么时候该搜证、每人的说法该怎么应对，本子里都写了。',
  )
  return lines.join('\n')
}
