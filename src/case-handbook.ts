export const CASE_HANDBOOK = `# 写一本：从「一个谜」到「一桌人能玩两小时」

**先读一个活例子。** 格式由 \`schema/case.schema.yml\` 定义（每一条字段注释都是从实测里逼出来的），
而最快的上手方式是打开 \`cases/07-夜场/case.yml\` 对着看——它是七本里最新的，六个人，注释最全。

写了之后跑这两样（都很快）：

\`\`\`bash
node scripts/check-case-syntax.mjs      # 两条 YAML 坑（引号数、* 开头）
pnpm test                               # 11 条结构检查：角色六段非空、恰好一个凶手、五个阶段 id…
\`\`\`

**那两样能查的都不在这里。** 这份手册装的是它们抓不到的——下面每一条都带着它是**哪一本踩出来的**。

# 一、五条真踩过的坑

## ① 收尾必须有一条物理上不可绕的证据

自检问句：**把真凶放到法庭上，检察官能拿出什么？**

- 答案是「他撒谎了」→ **不合格**（他改口「我记错了」就能脱身）。
- 要的是一条**物理上不可绕**的：一根断掉的挂绳、一条带了账号的日志、一截只脱开一头的护栏。

- **来由**：前六本**全部**缺过这一条，是后来一起补的。补的时候才发现：**每一本的凶手都已经
  想好了，而"怎么证明是他"那一栏是空的**——因为写凶手时想的是动机，不是证据。

## ② 动机链要经得起一句「为什么」

**每一个动作都要能回答「他为什么要这么做」，而那个答案要落在物理世界上。**

- **反例（case-06 的原文）**：「22:47 他在 12 层打印了那 11 页原始数据，打算碎掉再带走纸屑。」
  ——**电子数据打印出来再碎掉毫无意义**（删文件就行了）。而且同一段里还有个矛盾：
  「碎掉再带走纸屑」而纸篓里偏偏留了一角。
- **改法**：让「要处置的东西」是**纸**——真件碎掉，而他打的那 11 页是改过的版本、
  准备放回档案位**替掉**真件。于是「打印」不再是多余动作，它是一次**替换**的一半。
- **来由**：用户读本子时抓的，原话是「这不多此一举么？」。

## ③ 本子没给来源，AI 玩家就会自己补一个

角色本里写了「他知道 X」时，**要写清他是怎么知道的**。不写，玩的人会补一个最顺的假设——
通常是「你说过」。

- **真事**：case-01 里阿May 的 \`play\` 段写着「他有时间（他 21:45 才走）」，而她在桌上说的是
  「林默，**你说你 21:45 走的**」——而那时候真人一句话都没说。她确实知道那件事（她 21:50 进店，
  他刚走），**错的是引述方式**：她把自己知道的事安到了他嘴上。
- **改法两处**：① 角色本里补上来源（「你进店时他刚走，是柜台后面那位跟你说的」）；
  ② 给 AI 玩家的上台说明里加硬约束「别替任何人编他说过的话」。
- **来由**：用户开局第一句就发现了——他还没开口，AI 就引用了他的话。

## ④ 时刻字段要对着原话写

时间线的 \`at\` 是**按序排的**，写错一个数整张线就散了。而「换算」是这里最容易错的一步：

- 「八点一刻」= \`20:15\`、「八点整」= \`20:00\`、「十点二十」= \`22:20\`。
- **别按「夜里的第几个小时」去推**——那是错法的来源。
- **拿不准就别换算**，照原话的数字写。
- **来由**：用户报的——三条时间线里**三条都错**（「八点一刻到店」写成 21:00、「八点整走的」
  写成 22:30），而每一句 \`doing\` 里玩家自己都带着正确的时间。

## ⑤ 一个动作要是两步，就得把两步都写出来

工具设计上「取内容」与「记状态」经常是分开的（那本身没错：状态机只认 id，正文不经过它）。
而**写说明书的人很容易只写第一步**。

- **真事**：发线索是两步——\`jubensha_case action="clue"\` 捞正文贴到桌上、
  \`jubensha_state action="reveal" clues=[…]\` 把 id 记进局面。而房间页的搜证那一页**读的是第二步**。
  说明书只写了第一步，于是实测里 DM 在对话里念了线索，而那一页**从始至终是空的**。
- **判据**：**玩家看得见的那个界面读的是哪一步，那一步就必须出现在说明书里。**
- **来由**：我在 dev 里从头玩了一局才发现的（阶段条上「问诊」「搜证」都点着，而桌上一件物证都没有）。

# 二、怎么想一个本子

## 先定「真相的形状」，再定角色

一个好的推理本，真相是**一个动作**加**一条证据**：

- **动作**：「22:00 那一杆动了，钢丝带起的振动把松着一头的护栏震脱。」
- **证据**：「护栏只脱开一头，另一头螺丝还在孔里——那是**拆开**的样子，不是撞开的。」

而**误导是从真相长出来的**，不是另摆一个：每一个误导都该是「某个角色做了一件事，
而那件事看起来像杀人，其实不是」（他去拿自己的原稿、她去塞一封信、她在楼下等人）。

**别做「第二个真相」**。要给他心理负担，就让他「以为自己做了什么」（主观），而不是
「客观上真的可能做了什么」（那会造出第二个答案，而玩家会一直找到最后）。

## 情感落点要让它自己长出来

七本里最有效的做法：**在 \`emotional\` 里写一句谁都没被告知的话**，然后让它在桌上被说出来。

- **真事**：《夜场》的 \`emotional\` 里写着「那十分钟里，她其实是唯一一个没想害他的人」——
  那句话没给任何角色。而投票阶段，老团长对那个女孩说出来的是：
  「我不问你为什么不说。**我就说一句：那十分钟里，你没想害他。**」
- **判据**：写 \`emotional\` 时问自己——**这句话要是被某个角色自己说出来，它会成立吗？**
  会 → 那它就该留给桌上。

## 硬证据要「独占」，不要「指向」

- **好**：全团只有两个人有那个账号，而另一个当晚在台上（**独占**）。
- **差**：「那个人有动机」（**指向**——而桌上每个人都有动机，那就等于没指向）。

# 三、人数与节奏

- **四人是标准配置**，六人会更密（七本里有 1 本六人）。
- **六人的价值不在人多**：四个人的时候，一个人的不在场证明只能靠别人记不记得；六个人里
  **台前与后台是两条天然的对照线**——谁在台上（观众看得见）、谁在侧幕、谁在后台，
  五个人的位置能互相咬合，而凶手得在这张网里找一个空档。
- **六人要给每个人一条「能自己待着」的时间**（那才是空档），而**那条时间要有别人能看见的边界**
  （「21:50 到 22:15 我在侧幕，三个人能作证」）——不然整张网会糊成一片。
- **别把阶段写死**：剧本杀不是回合制，只有自我介绍按顺序。本子的 \`phases\` 只给五个框，
  而每一框里发生多少来回由桌上决定。

# 四、几个容易写坏的地方

- **角色本的 \`public\` 与 \`private\` 要真的分开**：\`public\` 是别人知道的（一句话），
  \`private\` 是他自己那一晚的经历（要具体到能对时间）。
- **\`play\` 段是给「玩的人」看的，不是给角色看的**：写他怎么演（说话方式、被问到时先说什么、
  哪一处破绽别掩饰），而不是再讲一遍剧情。
- **\`misdirections\` 写三条就够**，每条要指名道姓说清「他瞒的是什么、而那件事为什么无关」。
- **\`world_facts\` 是给玩家自主判断用的**：门怎么开、灯谁管、哪台机器记什么——**写那些能推翻
  某个说法的物理常识**，而不是世界观设定。
- **真凶那一位不要写成「最可疑的人」**：最可疑的那个该是玩家的位子（真人坐在最像凶手的位置上，
  而他什么也没做——那是七本通用的做法，也是最好玩的位子）。
`
